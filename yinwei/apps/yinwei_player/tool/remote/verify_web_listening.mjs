import assert from 'node:assert/strict';
import {readFile, writeFile} from 'node:fs/promises';
// Opt-in fixture QA. Set PLAYWRIGHT_MODULE to a module URL if not installed locally.
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = process.argv[2];
if (!root) throw Error('Supply the synthetic browser_preview_test.dart fixture directory');
const {origin} = JSON.parse(await readFile(`${root}/ui-preview.json`, 'utf8'));
assert.equal(new URL(origin).hostname, '127.0.0.1');
const browser = await chromium.launch({channel:'msedge',headless:true});
const context = await browser.newContext({viewport:{width:1280,height:900}});
await context.addInitScript(() => {
  window.qaSockets=[];
  const Original=window.WebSocket;
  window.WebSocket=class extends Original {constructor(...args){super(...args);window.qaSockets.push(this);}};
});
const page=await context.newPage(), errors=[];
page.on('pageerror', error=>errors.push(error.message));
const waitPlaying=()=>page.waitForFunction(()=>document.querySelector('#audio-status').textContent.startsWith('Playing laptop stereo'));
const results={kind:'automated synthetic Chromium fixture; not iPad listening'};
try {
  await page.goto(`${origin}/remote/signin`);
  await page.locator('[name=username]').fill('test-owner');
  await page.locator('[name=password]').fill('test-only-password');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#connection')?.textContent==='Connected to laptop');
  assert.equal(await page.getByText('Test iPad live audio',{exact:true}).count(),0);
  assert.equal(await page.locator('#listen').isEnabled(),true);
  await page.locator('#listen').click(); await waitPlaying();
  assert.equal(await page.locator('#listen').isEnabled(),false);
  results.authenticatedRendering=true;
  await page.locator('#stop-listening').click();
  assert.equal(await page.locator('#listen').isEnabled(),true);
  await page.locator('#listen').click(); await waitPlaying();
  results.stopRestart=true;
  await writeFile(`${root}/synthetic-live-state.json`,JSON.stringify({running:true,source:'B'}));
  await page.waitForFunction(()=>document.querySelector('#artist').textContent==='Synthetic Windows source B');
  await waitPlaying(); results.sourceChange=true;
  await page.evaluate(()=>window.qaSockets.findLast(s=>s.url.endsWith('/events')).close());
  await page.waitForFunction(()=>document.querySelector('#connection').textContent.includes('Connection lost'));
  assert.equal(await page.locator('#listen').isEnabled(),false);
  await page.locator('#reconnect').click();
  await page.waitForFunction(()=>document.querySelector('#connection').textContent==='Connected to laptop');
  await page.locator('#listen').click(); await waitPlaying(); results.reconnect=true;
  await page.screenshot({path:`${root}/landscape.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:`${root}/portrait.png`,fullPage:true}); results.layout=true;
  await writeFile(`${root}/synthetic-live-state.json`,JSON.stringify({running:false,source:'B'}));
  await page.waitForFunction(()=>document.querySelector('#audio-status').textContent.includes('Open a file'));
  assert.equal(await page.locator('#listen').isEnabled(),false);
  await writeFile(`${root}/synthetic-live-state.json`,JSON.stringify({running:true,source:'B'}));
  await page.waitForFunction(()=>!document.querySelector('#listen').disabled);
  await page.locator('#listen').click(); await waitPlaying(); results.liveStopStart=true;
  await page.locator('#signout').click();
  await page.waitForURL('**/remote/signin'); results.signout=true;
  assert.deepEqual(errors,[]); results.consoleErrors=errors;
  await writeFile(`${root}/browser-result.json`,JSON.stringify(results,null,2));
  console.log(JSON.stringify(results));
} finally {await browser.close();}
